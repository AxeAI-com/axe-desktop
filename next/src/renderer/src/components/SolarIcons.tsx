// The main area's icons (spec 0001): Solar Bold Duotone, the same names as Icons.tsx so a screen switches by its import
// path. The primary layer is the icon's colour; the secondary layer is the same colour at .35 and goes to 1 on hover,
// focus and the current item (`.axe-icon` in styles.css). The sidebar keeps Icons.tsx.

type P = Omit<SVGProps<SVGSVGElement>, "ref"> & { size?: number | string; title?: string }
type SolarComponent = (props: Record<string, unknown>) => React.ReactNode

function make(Solar: SolarComponent, defaultSize: number, extra = "") {
  return function SolarMainIcon({ size = defaultSize, className = "", title, ...rest }: P) {
    return <Solar size={size} className={`axe-icon ${extra} ${className}`.trim()} alt={title} aria-hidden={title ? undefined : true} focusable="false" {...rest} />
  }
}

